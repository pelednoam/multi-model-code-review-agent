def _gemini_enabled() -> bool:
    """Whether to use the gemini CLI for slot 3.

    Off by default. See ``_choose_command``: it has never produced a finding.
    Set ``REVIEW_USE_GEMINI=1`` (or true, yes, on) to try it again: read as the
    full-mode runner reads it.
    """
    return env_flag("REVIEW_USE_GEMINI")


def _agy_cmd(model: str) -> list[str]:
    """``agy`` as a reviewer: the shared, pinned invocation plus the result schema.

    The schema is the point of this backend over the gemini CLI. That slot's failure
    was answers the parser could not use; with ``--json-schema`` the shape is enforced
    by the CLI and arrives as ``structured_output``, not just requested in the prompt.
    """
    return agy_command(model, "--json-schema", agy_schema(RESULT_SCHEMA))


def _agy_workspace(repo: Path | None = None) -> Path | None:
    """An empty directory for agy to run in, outside the repository -- or None.

    The workspace is the one place the sandbox leaves writable, so it must not be the
    repository under review (``repo``, from ``--repo``, or else the directory the loop
    was started from) or this agent's own checkout -- nor inside any of them. Only
    the repository named: a loop started from / with --repo found every workspace
    "inside" its cwd, and agy never ran. ``mkdtemp``
    follows TMPDIR, which a project can point at a directory of its own, so the result
    is checked rather than assumed. Everything agy needs is in the prompt; empty also
    leaves nothing to wander through.
    """
    try:
        path = _scratch_dir("mmcra-agy-")
    except OSError:
        return None
    under_review = repo if repo is not None else Path.cwd()
    for root in {under_review.resolve(), REPO_ROOT.resolve()}:
        if path == root or root in path.parents:
            shutil.rmtree(path, ignore_errors=True)
            return None
    return path


#: Scratch directories of the round in progress. agy's state copy holds its sign-in
#: token, so they go when the round's reviewers are done, not when the loop is -- and
#: whatever a round leaves, the loop's exit takes.
_ROUND_SCRATCH: list[Path] = []


def _scratch_dir(prefix: str) -> Path:
    """A temporary directory removed when this round ends, or failing that, the loop."""
    path = Path(tempfile.mkdtemp(prefix=prefix)).resolve()
    _ROUND_SCRATCH.append(path)
    return path


def _release_scratch() -> None:
    """Remove the round's scratch directories, saying which could not be removed.

    One that cannot be removed stays listed, for the loop's exit to try again, and is
    named: agy's state copy holds its sign-in token, and forgetting it silently left
    the copy on disk with nothing said.
    """
    with signals_deferred():
        kept = []
        for path in _ROUND_SCRATCH:
            if not _remove_tree(path):
                kept.append(path)
                print(f"  WARNING: could not remove {path}; remove it by hand")
        _ROUND_SCRATCH[:] = kept


def _remove_tree(path: Path) -> bool:
    """Remove ``path`` and everything in it, even what was made read-only."""
    shutil.rmtree(path, ignore_errors=True)
    if os.path.lexists(path):
        # A directory made read-only -- by a reviewer, say -- refuses to give up its
        # entries; made writable first, top down, it does.
        with contextlib.suppress(OSError):
            os.chmod(path, 0o700)
        for root, dirs, _ in os.walk(path):
            for name in [root, *(os.path.join(root, d) for d in dirs)]:
                with contextlib.suppress(OSError):
                    if not os.path.islink(name):
                        os.chmod(name, 0o700)
        shutil.rmtree(path, ignore_errors=True)
    return not os.path.lexists(path)


atexit.register(_release_scratch)


def _codex_extra_args() -> list[str]:
    """Build the extra ``codex exec`` flags from CODEX_* env vars.

    Always pins the two safety flags (see below), then layers the model
    overrides on top.

    Model defaults: whatever ``~/.codex/config.toml`` already has (typically
    ``model = "gpt-5.5"`` and ``model_reasoning_effort = "medium"`` for
    ChatGPT Plus users).

    Overrides:
      - ``CODEX_MODEL=<id>``       -- e.g. ``gpt-5.5``, ``gpt-5.5-codex``
      - ``CODEX_REASONING_EFFORT=<level>`` -- ``low``, ``medium``, or
        ``high``. ``high`` is the equivalent of "GPT-5.5 Pro" in the
        ChatGPT web UI: same base model, deeper reasoning (slower, more
        tokens per query). Worth it for spec-contract review and deep
        architectural questions; medium is usually fine for line-level
        correctness review.
    """
    import os

    # NON-NEGOTIABLE, and deliberately not overridable by env:
    #
    #   -s read-only            the reviewer must not be able to edit the code it reviews.
    #                           The tool previously passed NO sandbox flag and relied on
    #                           codex's default, which varies by host and config.
    #   approvals_reviewer=user a global `approvals_reviewer = "auto_review"` in the user's
    #                           ~/.codex/config.toml auto-approves the model's escalation
    #                           requests "using the workspace-write sandbox" (codex's own
    #                           wording) and thereby OVERRIDES -s read-only. Verified side
    #                           by side on codex-cli 0.153.4: with auto_review the write
    #                           succeeded; with "user" the same prompt got
    #                           "Read-only file system". Pinning it here means a reviewer's
    #                           confinement no longer depends on a user's global settings.
    #
    # This is belt AND braces: backends.codex_is_confined() still canary-tests the result,
    # because a flag that is silently overridden is exactly the failure being defended against.
    args: list[str] = ["-s", "read-only", "-c", 'approvals_reviewer="user"']
    model = os.environ.get("CODEX_MODEL")
    if model:
        args.extend(["-m", model])
    effort = os.environ.get("CODEX_REASONING_EFFORT")
    if effort:
        args.extend(["-c", f"model_reasoning_effort={effort}"])
    return args


def _choose_command(
    slot: int,
    prompt_path: Path,
    out_dir: Path,
    backends: dict[str, bool],
    prefer_hermes: bool = False,
) -> tuple[list[str], str | None] | None:
    """Pick the command for a reviewer slot.

    Default precedence (``prefer_hermes=False``): local CLIs first --
    they're free (existing subscriptions) and manage their own auth.
    Hermes/Bedrock is the paid API path; only chosen as a last resort.

    Bedrock opt-in (``prefer_hermes=True``): Hermes/Bedrock first for
    Anthropic reviewers. Used by regulated codebases that need
    data-at-rest in their AWS account.

    Returns ``(cmd, rebuild_label)``, where ``rebuild_label`` is set when
    the chosen backend needs the prompt to be rebuilt with a different
    model label (slot 2's hermes-haiku path, and agy, which names the model
    it runs). Returns ``None`` if no backend is available.
    """
    if prefer_hermes and backends["hermes"]:
        if slot in (1, 4):
            return _hermes_cmd(prompt_path, _OPUS_BEDROCK), None
        if slot == 2:
            return _hermes_cmd(prompt_path, _HAIKU_BEDROCK), "claude-haiku-4.5"
        if slot == 3:
            return _hermes_cmd(prompt_path, _SONNET_BEDROCK), None

    if slot == 2 and backends["codex"]:
        result_path = out_dir / f"codex-out-{slot}.txt"
        return [
            "codex",
            "exec",
            *_codex_extra_args(),
            "-o",
            str(result_path),
            "-",
        ], None
    # A project that pinned Bedrock did so to keep its code with providers it chose;
    # if Hermes is unavailable, slot 3 must not fall to a Google default it never
    # agreed to. There, agy runs only when asked for by name (REVIEW_USE_AGY=1).
    agy_allowed = not prefer_hermes or env_flag("REVIEW_USE_AGY")
    if slot == 3 and backends.get("agy") and agy_allowed:
        # Ahead of gemini: both are Google, and this one can be held to the schema.
        # backends["agy"] is only true once agy is switched on and its sandbox check
        # has passed, and agy_model_choice()[0] picks once per run, so every round runs the
        # same model.
        model = agy_model_choice()[0]
        if model:
            # The schema is read from this checkout, which may be the tree under
            # review; a missing or broken one costs slot 3 its backend, not the round.
            try:
                return _agy_cmd(model), model
            except (OSError, ValueError) as exc:
                print(f"  agy: result schema unusable ({exc}); trying next backend")
    if slot == 3 and _gemini_enabled() and backends["gemini"]:
        # Opt-in, because in practice it does not review. Across eight rounds
        # on a real project this slot returned zero findings every single time,
        # while the other three returned six to nineteen each. `stderr` shows
        # why: the gemini CLI treats the prompt as a task and goes exploring the
        # repository with its own tools, finishing a 200 KB diff in sixty
        # seconds where the Claude reviewers take six minutes. Until that is
        # understood, the default for slot 3 is the backend that works.
        return [
            "gemini",
            "--model",
            _gemini_model(),
            "--approval-mode",
            "plan",
            "--skip-trust",
        ], _gemini_model()
    if backends["claude"]:
        return _claude_cmd(slot), None

    # Last-resort Hermes paths if no local CLI matched.
    if slot in (1, 4) and backends["hermes"]:
        return _hermes_cmd(prompt_path, _OPUS_BEDROCK), None
    if slot == 2 and backends["hermes"]:
        return _hermes_cmd(prompt_path, _HAIKU_BEDROCK), "claude-haiku-4.5"
    if slot == 3 and backends["hermes"]:
        return _hermes_cmd(prompt_path, _SONNET_BEDROCK), None
    return None


def _stdin_backends() -> tuple[str, ...]:
    """CLI backends that accept the prompt on stdin (not via filepath)."""
    return ("codex", "gemini", "claude", "agy")


@dataclass(frozen=True)
class _Round:
    """What every reviewer in a round is launched with."""

    diff: str
    audit: str
    context: str
    round_dir: Path
    backends: dict[str, bool]
    prefer_hermes: bool = False
    #: The repository under review, which no reviewer's writable directory may be in.
    repo: Path | None = None
    #: Where the reviewers write while they run (``_private_outputs``); round_dir
    #: when None.
    out_dir: Path | None = None

    @property
    def writes_to(self) -> Path:
        return self.out_dir or self.round_dir


class _Picked(NamedTuple):
    """The backend that answers a slot, ready to launch."""

    #: The command, wrapper included.
    cmd: list[str]
    #: The CLI that answers, which decides how its output is read.
    backend: str
    #: The model the prompt should name; None for the lens's own.
    label: str | None
    #: Its working directory; None for the round's.
    workspace: Path | None


def _launch_one(
    slot: int,
    lens_args: tuple[str, str, str, str],
    round_: _Round,
    register: Callable[[ReviewerProc], object] | None = None,
) -> ReviewerProc | None:
    """Launch a single reviewer subprocess. Return tracking tuple or None.

    ``register`` is handed the tracking tuple the moment the reviewer exists
    (``_spawn``).
    """
    picked = _pick_backend(slot, round_)
    if picked is None:
        print(f"  R{slot}: SKIPPED (no backend)")
        return None
    backend = picked.backend
    lens, focus, rv, default_label = lens_args
    model = picked.label or default_label
    prompt = build_reviewer_prompt(
        lens, focus, rv, model, round_.diff, round_.audit, round_.context
    )
    if backend == "agy":
        # Told to call no tools; the prompt file records that it was.
        prompt = AGY_PREAMBLE + prompt
        # On by default, so said whenever it runs: this is where the diff leaves.
        print(f"  R{slot}: {AGY_EGRESS}")
    # The record of what the reviewer was sent.
    (round_.round_dir / f"prompt-{slot}.txt").write_text(prompt)
    # Which backend answered, for a person reading the round. The loop goes by what
    # it launched (``launch_reviewers`` returns it), not by this file.
    (round_.round_dir / f"backend-{slot}.txt").write_text(backend)
    fed = None
    if backend in _stdin_backends():
        fed = agy_message(prompt) if backend == "agy" else prompt
    proc, out_f, err_f = _spawn(
        slot, picked.cmd, backend, picked.workspace, fed, round_.writes_to, register
    )
    return slot, proc, backend, out_f, err_f


def _pick_backend(slot: int, round_: _Round) -> _Picked | None:
    """The backend for ``slot`` -- or None if none is available.

    If agy is chosen but cannot be set up, the slot gets the backend it would have had
    without agy, as the routing tables say: an empty slot 3 every round never
    converges. The prompt is built once the backend is settled, not per attempt.
    """
    prompt_path = round_.round_dir / f"prompt-{slot}.txt"
    first, without_agy = round_.backends, {**round_.backends, "agy": False}
    for backends in (first, without_agy):
        choice = _choose_command(
            slot, prompt_path, round_.writes_to, backends, round_.prefer_hermes
        )
        if choice is None:
            return None
        cmd, label = choice
        if cmd[0] != "agy":
            return _Picked(cmd, cmd[0], label, None)
        prepared = _prepare_agy(slot, cmd, round_.repo)
        if prepared is not None:
            wrapped, workspace = prepared
            return _Picked(wrapped, "agy", label, workspace)
    return None


def _spawn(
    slot: int,
    cmd: list[str],
    backend: str,
    workspace: Path | None,
    fed: str | None,
    out_dir: Path,
    register: Callable[[ReviewerProc], object] | None = None,
) -> tuple[subprocess.Popen[str], IO[str], IO[str]]:
    """Start ``cmd`` with ``fed`` on its stdin, writing to the slot's output files.

    Until the caller tracks the reviewer it cannot clean it up, so an interrupt in
    here -- SIGTERM is one -- unwinds through ``failed``, which stops the reviewer
    from the moment it exists: closing its input is in here too. ``register`` hands
    the reviewer over while ``failed`` still guards it: tracked by the time this
    returned, it was not tracked between returning and the caller's append, and an
    interrupt there left it running. The output handles outlive this function on
    success; launch_reviewers closes them.
    """
    with contextlib.ExitStack() as failed:
        out_f = failed.enter_context(_output(out_dir / f"raw-{slot}.txt"))
        err_f = failed.enter_context(_output(out_dir / f"stderr-{slot}.txt"))
        with _feed(fed) as feed:
            proc = subprocess.Popen(
                cmd,
                cwd=workspace,
                stdin=feed,
                stdout=out_f,
                stderr=err_f,
                text=True,
                encoding="utf-8",
                errors="replace",
                # Its own process group, so a timeout can take down the helpers a CLI
                # started rather than orphaning them to finish unread.
                start_new_session=True,
            )
            failed.callback(_stop, proc)
        if register is not None:
            register((slot, proc, backend, out_f, err_f))
        print(f"  R{slot}: launched via {backend}")
        failed.pop_all()
    return proc, out_f, err_f


def _prepare_agy(
    slot: int, cmd: list[str], repo: Path | None
) -> tuple[list[str], Path] | None:
    """agy's command inside its sandbox, and its workspace -- or None, saying why."""
    workspace = _agy_workspace(repo)
    if workspace is None:
        print(f"  R{slot}: agy has no workspace outside the repo (see TMPDIR)")
        return None
    if agy_unsandboxed():
        return cmd, workspace
    try:
        state = agy_seed_state(_scratch_dir("mmcra-agy-state-"))
        sandbox = agy_wrapper(workspace, state)
    except OSError as exc:
        print(f"  R{slot}: could not prepare agy's sandbox ({exc})")
        return None
    # The startup check described the host as it was then; what has appeared since
    # -- a session bus, a socket, an X server -- is checked again here.
    failure = agy_reachable(sandbox, workspace)
    if failure:
        print(f"  R{slot}: agy not launched -- {failure}")
        return None
    return [*sandbox, *cmd], workspace


def _output(path: Path) -> IO[str]:
    """A reviewer's output file, open for it to write."""
    return open(path, "w", encoding="utf-8", errors="replace")  # noqa: SIM115


@contextlib.contextmanager
def _feed(text: str | None) -> Iterator[IO[str] | None]:
    """``text`` as a reviewer's stdin: an unlinked file, closed once it is handed over.

    A file, not a pipe: a pipe holds 64 KB, so a large prompt blocked the launch loop
    until the reviewer read it -- forever, if it never did, with the deadline not yet
    started -- and one that exited unread raised BrokenPipeError.
    """
    if text is None:
        yield None
        return
    with tempfile.TemporaryFile("w+", encoding="utf-8") as feed:
        feed.write(text)
        feed.seek(0)
        yield feed


def _stop(proc: subprocess.Popen[str]) -> None:
    """Kill a reviewer and its group, then reap it -- waiting, but not forever: a
    process stuck in the kernel ignores even SIGKILL, and shutdown must not hang."""
    _kill_group(proc)
    with contextlib.suppress(subprocess.TimeoutExpired):
        proc.wait(timeout=10)


def _exit_status(proc: subprocess.Popen[str]) -> int | None:
    """The reviewer's exit status once it has exited -- without reaping it.

    Reaped, its pid, which is also its process group's number, is free for the system
    to hand to someone else's new session -- a shell, an ssh login -- and the group
    kill at the end of the round would reach that. Left a zombie until ``_stop``, the
    number stays this run's, and so does everything the kill can reach.

    Where there is no ``os.waitid`` -- macOS before Python 3.13 -- it is reaped as
    before, and the helpers of a reviewer that exited are left to finish on their own.
    """
    if proc.returncode is not None:
        return proc.returncode
    if not hasattr(os, "waitid"):
        return proc.poll()
    try:
        info = os.waitid(os.P_PID, proc.pid, os.WEXITED | os.WNOHANG | os.WNOWAIT)
    except ChildProcessError:
        return proc.poll()
    if info is None:
        return None
    return info.si_status if info.si_code == os.CLD_EXITED else -info.si_status


def launch_reviewers(
    round_dir: Path,
    diff: str,
    audit: str,
    context: str,
    backends: dict[str, bool],
    prefer_hermes: bool = False,
    repo: Path | None = None,
) -> dict[int, str]:
    """Launch 4 reviewers in parallel, write raw outputs to round_dir.

    ``repo`` is the repository under review, which no reviewer's writable scratch
    directory may be inside.

    Returns the CLI that answered each slot launched, which decides how its output is
    read (``extract_results``). From memory, not from ``backend-N.txt``: that file is
    in round_dir, which a reviewer with a file tool -- hermes runs ``--yolo`` -- can
    write, and a slot it marked agy's would be read as agy's verdict.

    Reports progress while it waits. Four models on a large diff is fifteen
    minutes of silence otherwise, during which the only way to tell a working
    reviewer from a hung one was to guess at the process table -- and `pgrep`
    finds other people's CLI sessions on the same machine, so the guess is
    wrong as often as it is right.
    """
    procs: list[ReviewerProc] = []
    out_dir: Path | None = None
    # A plain SIGTERM or SIGHUP would skip the finally below, leaving the reviewers
    # running and agy's token copy on disk.
    with signals_unwind():
        try:
            out_dir = _scratch_dir("mmcra-out-")
            round_ = _Round(
                diff, audit, context, round_dir, backends, prefer_hermes, repo, out_dir
            )
            for i, lens_args in enumerate(_LENSES, 1):
                _launch_one(i, lens_args, round_, procs.append)
            _await_reviewers(procs, out_dir, diff.count("\n") + 1)
            return {slot: backend for slot, _, backend, _, _ in procs}
        finally:
            # Every group, finished or not: a reviewer that exited can leave helpers
            # running in its group, spending quota and writing its output. Each
            # leader is still unreaped (``_exit_status``), so each number is still
            # this run's group. A second signal waits until this is done.
            with signals_deferred():
                for _, proc, _, out_f, err_f in procs:
                    _stop(proc)
                    out_f.close()
                    err_f.close()
                if out_dir is not None:
                    _publish_outputs(out_dir, round_dir)
                _release_scratch()


#: What a reviewer writes while it runs, per slot: stdout, stderr, codex's answer.
_OUTPUTS = ("raw-{}.txt", "stderr-{}.txt", "codex-out-{}.txt")


def _publish_outputs(out_dir: Path, round_dir: Path) -> None:
    """Copy what the reviewers wrote into round_dir, once every one has stopped.

    They write into a private directory of the round's (``_scratch_dir``), not into
    round_dir: there, one reviewer with a file tool -- hermes runs ``--yolo`` -- could
    write another's output while both ran, and answer for it. Copied only when no
    reviewer is left to write, and extraction reads the copies. A reviewer running as
    the same user could still find the private directory; this takes away the
    obvious path, and docs/ensemble-review.md says so.
    """
    for slot in range(1, len(_LENSES) + 1):
        for pattern in _OUTPUTS:
            name = pattern.format(slot)
            # Whatever is there already was not written by this round's reviewer --
            # say, a codex answer planted for a codex that wrote none -- so it goes
            # whether or not there is a copy to replace it.
            (round_dir / name).unlink(missing_ok=True)
            if (out_dir / name).is_file():
                shutil.copyfile(out_dir / name, round_dir / name)


def _await_reviewers(procs: list[ReviewerProc], out_dir: Path, n_lines: int) -> None:
    """Wait for every reviewer, reporting who is still working.

    One deadline for the whole round, not one per reviewer. `proc.wait(timeout)`
    per slot in turn gave each its own fresh budget starting when its turn came,
    so a reviewer behind a slow one silently got double the timeout and
    "TIMEOUT after 600s" was printed after fifteen real minutes.

    The deadline scales with the diff, because the reviewer that runs out of
    time is the one with the most to say.
    """
    budget = reviewer_timeout(n_lines)
    deadline = time.monotonic() + budget
    started = time.monotonic()
    pending = {slot: tracked for tracked in procs for slot in (tracked[0],)}
    last_report = 0.0
    cpu: dict[int, float] = {}

    while pending:
        for slot, tracked in list(pending.items()):
            _, proc, backend, out_f, err_f = tracked
            rc = _exit_status(proc)
            if rc is None:
                continue
            out_f.close()
            err_f.close()
            del pending[slot]
            if rc != 0:
                print(f"  R{slot}: exit {rc} ({backend}) -- see stderr-{slot}.txt")
        if not pending:
            break
        now = time.monotonic()
        if now >= deadline:
            _give_up(pending, out_dir, budget)
            return
        if now - last_report >= PROGRESS_INTERVAL:
            print(_progress(procs, pending, out_dir, now - started, cpu))
            last_report = now
        time.sleep(POLL_INTERVAL)


def _give_up(pending: dict[int, ReviewerProc], out_dir: Path, budget: int) -> None:
    """Stop waiting, and take what arrives anyway.

    ``proc.kill()`` kills the process we started, which is not always the one
    doing the work: a CLI that shells out to a helper leaves it running, and the
    review lands minutes later. That was not theoretical -- a reviewer killed at
    ten minutes wrote fifteen findings, four of them critical, at nineteen. The
    loop had collected results nine minutes earlier and threw the whole review
    away.

    So: kill the process *group* where the platform has them, then keep looking
    for codex's answer file for a short grace period before giving up.
    """
    for slot, tracked in pending.items():
        _, proc, _, out_f, err_f = tracked
        _kill_group(proc)
        out_f.close()
        err_f.close()
        print(f"  R{slot}: TIMEOUT after {budget}s")

    # Only codex's answer is a file of its own that can still land; the others'
    # are their stdout, which ended with them.
    waiting = {
        slot
        for slot, (_, _, backend, _, _) in pending.items()
        if backend == "codex" and not _has_codex_answer(out_dir, slot)
    }
    if not waiting:
        return
    print(f"  ...watching {LATE_RESULT_GRACE}s for a late result from {_slots(waiting)}")
    until = time.monotonic() + LATE_RESULT_GRACE
    while waiting and time.monotonic() < until:
        for slot in sorted(waiting):
            if _has_codex_answer(out_dir, slot):
                print(f"  R{slot}: arrived after the deadline -- kept")
                waiting.discard(slot)
        time.sleep(POLL_INTERVAL)
    if waiting:
        print(f"  {_slots(waiting)}: nothing arrived; see stderr-N.txt")


def _slots(slots: set[int]) -> str:
    """A set of reviewer slots, named the way the log names them."""
    return ", ".join(f"R{slot}" for slot in sorted(slots))


def _has_codex_answer(out_dir: Path, slot: int) -> bool:
    """Whether codex, the one reviewer that writes its answer to a file of its own
    (-o), has written it, with something in it."""
    path = out_dir / f"codex-out-{slot}.txt"
    return path.exists() and path.stat().st_size > 0


def _kill_group(proc: subprocess.Popen[str]) -> None:
    """Kill the reviewer and anything it started.

    A CLI that spawns a helper leaves it running when only the parent is
    killed, and that orphan goes on burning quota for a review nobody will
    read. ``start_new_session`` at launch puts each reviewer in its own process
    group so the whole tree can be taken down together.
    """
    # The group by the reviewer's own pid -- start_new_session made it the group's
    # leader -- since getpgid() fails once the leader has exited, and its helpers
    # may not have. Only while the leader is unreaped: after that the number may
    # already belong to someone else (``_exit_status``).
    if proc.returncode is not None:
        return
    with contextlib.suppress(OSError):
        os.killpg(proc.pid, signal.SIGKILL)


def _progress(
    procs: list[ReviewerProc],
    pending: dict[int, ReviewerProc],
    out_dir: Path,
    elapsed: float,
    cpu: dict[int, float],
) -> str:
    """One line saying who is still working, and what says so.

    Two signals, because neither alone covers both kinds of backend:

    - **Output size.** `codex` streams progress to stderr, so its file grows
      while it works. Both streams count: it writes its *result* to stdout, so
      stdout stays empty until the very end and looked hung for its whole run.
    - **CPU time.** `claude -p --output-format json` buffers everything and
      writes at the end, so its output is 0 bytes from start to finish and size
      cannot tell "thinking" from "hung". Rising CPU can.

    Neither is a guarantee; together they are the difference between a line that
    reports progress and one that reports only completion.
    """
    parts: list[str] = []
    for slot, proc, backend, _out, _err in procs:
        if slot not in pending:
            parts.append(f"R{slot}({backend}) done")
            continue
        parts.append(f"R{slot}({backend}) {_working(out_dir, slot, proc, cpu)}")
    return f"  ...{_clock(elapsed)} · " + " · ".join(parts)


def _working(
    out_dir: Path, slot: int, proc: subprocess.Popen[str], cpu: dict[int, float]
) -> str:
    """What this reviewer has to show for itself since the last report."""
    written = _bytes_written(out_dir, slot)
    used = _cpu_seconds(proc.pid)
    if used is None:
        return _size(written)
    burned = used - cpu.get(slot, 0.0)
    cpu[slot] = used
    # A tenth of a second between reports thirty seconds apart is a process
    # waiting on a network reply, which is what these spend most of their time
    # doing. Anything above it is work.
    return f"{_size(written)}" if burned < _BUSY_SECONDS else f"{_size(written)} busy"


#: CPU seconds between reports above which a reviewer is certainly working.
_BUSY_SECONDS = 0.1


def _cpu_seconds(pid: int) -> float | None:
    """CPU time this process and its children have used, or None if unknowable.

    Linux only, and optional by design: everything else still gets the output
    size, which is the signal that matters for the backends that stream.
    """
    try:
        stat = Path(f"/proc/{pid}/stat").read_text(encoding="utf-8")
        # The command name is parenthesised and may contain spaces, so the
        # fields after it are what can be split safely.
        fields = stat.rsplit(") ", 1)[1].split()
        ticks = sum(int(fields[index]) for index in (11, 12, 13, 14))
    except (OSError, IndexError, ValueError):
        return None
    return ticks / os.sysconf("SC_CLK_TCK")


def _bytes_written(out_dir: Path, slot: int) -> int:
    """How much this reviewer has written: stdout, stderr and codex's answer."""
    total = 0
    for pattern in _OUTPUTS:
        path = out_dir / pattern.format(slot)
        if path.exists():
            total += path.stat().st_size
    return total


def _size(written: int) -> str:
    """Bytes, roughly, for a progress line."""
    return f"{written / 1024:.0f}K" if written >= 1024 else f"{written}B"


def _clock(seconds: float) -> str:
    """Elapsed time as a person reads it."""
    return f"{int(seconds) // 60}m{int(seconds) % 60:02d}s"
